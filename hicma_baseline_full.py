"""## 3) دوال التجهيز: العينة والتقسيم ونسختا الصور"""

def make_split(seed):
    """عينة متوازنة تقريباً + تقسيم طبقي 80/10/10، كلها تعتمد على الـ seed"""
    parts = [g if N_PER_CLASS is None else g.sample(min(len(g), N_PER_CLASS), random_state=seed)
             for _, g in allrows.groupby("style")]
    sample = pd.concat(parts).reset_index(drop=True)
    sample["y"] = sample["style"].map({s: i for i, s in enumerate(STYLES)})
    ys = sample["y"].values
    idx = np.arange(len(sample))
    tr, tmp = train_test_split(idx, test_size=0.2, stratify=ys, random_state=seed)
    va, te = train_test_split(tmp, test_size=0.5, stratify=ys[tmp], random_state=seed)
    sample["split"] = "train"
    sample.loc[va, "split"] = "val"
    sample.loc[te, "split"] = "test"
    return sample, ys, tr, va, te

def fit(path):
    """تغيير الحجم مع الحفاظ على النسبة + حشو أبيض إلى 128x768"""
    im = Image.open(path).convert("RGB")
    r = min(W / im.width, H / im.height)
    im = im.resize((max(1, int(im.width * r)), max(1, int(im.height * r))), Image.LANCZOS)
    canvas = Image.new("RGB", (W, H), (255, 255, 255))
    canvas.paste(im, ((W - im.width) // 2, (H - im.height) // 2))
    return canvas

def remove_bg(pil):
    """نبقي بكسلات الكتابة بألوانها الأصلية ونحول كل الباقي إلى أبيض"""
    img = np.array(pil)
    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    bg = cv2.medianBlur(gray, 51)
    diff = cv2.absdiff(gray, bg)
    _, mask = cv2.threshold(diff, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
    mask = cv2.dilate(mask, np.ones((3, 3), np.uint8))
    out = np.full_like(img, 255)
    out[mask > 0] = img[mask > 0]
    return Image.fromarray(out)

_cache = {}
def get_imgs(paths):
    for p in paths:
        if p not in _cache:
            f = fit(p)
            _cache[p] = (f, remove_bg(f))
    return [_cache[p][0] for p in paths], [_cache[p][1] for p in paths]

