"""## 4) تعريف التدريب"""

import torch, torch.nn as nn
from torch.utils.data import Dataset, DataLoader
from torchvision import models, transforms
from sklearn.metrics import accuracy_score, f1_score, confusion_matrix, classification_report, ConfusionMatrixDisplay

device = "cuda" if torch.cuda.is_available() else "cpu"
HARDWARE = torch.cuda.get_device_name(0) if device == "cuda" else "CPU"
print("device:", device, "|", HARDWARE)

def set_seed(s):
    random.seed(s); np.random.seed(s); torch.manual_seed(s); torch.cuda.manual_seed_all(s)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False

norm = transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
tf_train = transforms.Compose([transforms.RandomRotation(5, fill=(255, 255, 255)),
                               transforms.ToTensor(), norm])
tf_eval = transforms.Compose([transforms.ToTensor(), norm])

class DS(Dataset):
    def __init__(self, imgs, ys, tf): self.imgs, self.ys, self.tf = imgs, ys, tf
    def __len__(self): return len(self.imgs)
    def __getitem__(self, i): return self.tf(self.imgs[i]), int(self.ys[i])

def make_loader(imgs, ys, ids, tf, shuffle, seed):
    g = torch.Generator().manual_seed(seed)
    return DataLoader(DS([imgs[i] for i in ids], ys[ids], tf), batch_size=BATCH,
                      shuffle=shuffle, generator=g, num_workers=0)

def predict(model, dl):
    model.eval(); P, T = [], []
    with torch.no_grad():
        for xb, yb in dl:
            P += model(xb.to(device)).argmax(1).cpu().tolist(); T += yb.tolist()
    return np.array(P), np.array(T)

def macro_f1(t, p):
    return f1_score(t, p, average="macro", labels=LABELS, zero_division=0)

def run(imgs, name, seed, ys, tr, va, te):
    set_seed(seed)
    t_start = time.time()
    model = models.resnet18(weights="IMAGENET1K_V1")
    model.fc = nn.Linear(512, len(STYLES))
    model.to(device)
    opt = torch.optim.Adam(model.parameters(), lr=LR)
    lossf = nn.CrossEntropyLoss()
    dl_tr = make_loader(imgs, ys, tr, tf_train, True, seed)
    dl_va = make_loader(imgs, ys, va, tf_eval, False, seed)
    dl_te = make_loader(imgs, ys, te, tf_eval, False, seed)
    best_f1, best_state = -1, None
    for ep in range(1, EPOCHS + 1):
        model.train(); tot = 0
        for xb, yb in dl_tr:
            xb, yb = xb.to(device), yb.to(device)
            opt.zero_grad(); loss = lossf(model(xb), yb); loss.backward(); opt.step()
            tot += loss.item() * len(xb)
        p, t = predict(model, dl_va)
        f1 = macro_f1(t, p)
        if f1 > best_f1:
            best_f1, best_state = f1, copy.deepcopy(model.state_dict())
        if ep == 1 or ep % 5 == 0:
            print(f"  [seed {seed} | {name}] epoch {ep:02d} | train loss {tot / len(tr):.4f} | val macro-F1 {f1:.3f}")
    train_min = (time.time() - t_start) / 60
    model.load_state_dict(best_state)          # أفضل checkpoint حسب Macro-F1 على الـ validation
    p, t = predict(model, dl_te)               # التقييم على الـ test مرة وحدة
    return {"seed": seed, "name": name, "pred": p, "true": t, "best_val_f1": best_f1, "train_min": train_min}

"""## 5) تشغيل التجربة على كل الـ seeds"""

all_results = []
t0 = time.time()
for seed in SEEDS:
    sample, ys, tr, va, te = make_split(seed)
