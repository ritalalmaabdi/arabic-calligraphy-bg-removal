def norm_style(v):
    v = str(v).strip().lower()
    for k, alts in ALT.items():
        if v in alts:
            return k
    return None

def list_images(d):
    return [f for f in glob.glob(d + "/**/*", recursive=True)
            if f.lower().endswith(IMG_EXT)
            and not os.path.basename(f).startswith("._") and "__MACOSX" not in f]

def read_set(s):
    dirs = [p for p in glob.glob(f"HICMA/**/{s}", recursive=True)
            if os.path.isdir(p) and "__MACOSX" not in p]
    assert dirs, f"ما لقيت مجلد {s}"
    d = dirs[0]
    imgs = list_images(d)
    by_name = {os.path.basename(p): p for p in imgs}
    by_stem = {os.path.splitext(os.path.basename(p))[0]: p for p in imgs}
    def match(v):
        v = str(v).strip()
        return by_name.get(v) or by_stem.get(os.path.splitext(v)[0])
    lab = [f for f in glob.glob(d + "/labels*") if os.path.isfile(f)]
    assert lab, f"ما لقيت ملف labels في {s}"
    found = None
    for sep in ("\t", ",", ";", "|"):
        try:
            df = pd.read_csv(lab[0], sep=sep, dtype=str, header=None,
                             on_bad_lines="skip", encoding="utf-8-sig")
        except Exception:
            continue
        if df.shape[1] < 2:
            continue
        f_col = max(df.columns, key=lambda c: df[c].map(match).notna().mean())
        s_col = max(df.columns, key=lambda c: df[c].map(norm_style).notna().mean())
        if (df[f_col].map(match).notna().mean() > 0.5
                and df[s_col].map(norm_style).notna().mean() > 0.5):
            found = (df, f_col, s_col)
            break
    if not found:
        print(open(lab[0], encoding="utf-8-sig", errors="ignore").read()[:600])
        raise ValueError(f"ما قدرت أقرأ ملف labels في {s}. ارسلوا لي الناتج أعلاه.")
    df, f_col, s_col = found
    rows = []
    for fn, st in zip(df[f_col], df[s_col]):
        p, y = match(fn), norm_style(st)
        if p and y:
            rows.append((s, p, y))
    print(f"{s}: {len(imgs)} images, {len(rows)} labelled rows")
    return pd.DataFrame(rows, columns=["set", "path", "style"])

